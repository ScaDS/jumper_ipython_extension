"""Build the standalone script that replays a session and times one cell.

The script drives the same ``magic_adapter`` hooks a live notebook does, so the
numbers it exports come from the same monitor and the same ``CellHistory`` as
the original run - which is the whole point: the variant has to be measured the
way the baseline was.
"""
import re
from pathlib import Path
from textwrap import dedent

from jumper_extension.adapters.script_writer import is_pure_magic_cell, transform_cell_code

# Written above each cell so a traceback can be traced back to the cell it came
# from. A replay that fails in the prefix has not measured anything and has said
# nothing about the code under review, and the two have to be told apart.
_PREFIX_MARKER = "# --- cell {index} ---"
_TARGET_MARKER = "# --- cell under test ---"
_CELL_MARKER = re.compile(r"^# --- cell (\d+) ---$")

_HEADER = '''\
#!/usr/bin/env python3
"""Auto-generated by the JUmPER AI reviewer benchmark. Not meant to be edited."""
from jumper_extension.core.service import build_perfmonitor_magic_adapter
from jumper_extension.adapters.ai_reviewer.benchmark.fingerprint import dump

magic_adapter = build_perfmonitor_magic_adapter(
    plots_disabled=True,
    plots_disabled_reason="Plotting disabled in the benchmark script.",
    display_disabled=True,
    display_disabled_reason="Display disabled in the benchmark script.",
)
magic_adapter.perfmonitor_start({interval!r})
'''

_FOOTER = '''
dump({names!r}, globals(), {fingerprint_path!r})
magic_adapter.perfmonitor_stop("")
magic_adapter.export_session({session_path!r})
'''


_CHECKPOINT_HEADER = '''\
#!/usr/bin/env python3
"""Auto-generated by the JUmPER AI reviewer benchmark. Not meant to be edited."""
import time as _jumper_time
from jumper_extension.adapters.ai_reviewer.benchmark import dill_state as _jumper

# The prefix runs in a namespace of its own, so nothing the user binds can
# collide with this script's bookkeeping - and nothing of ours ends up in the
# checkpoint. Cells go through the same hooks the full replay uses, because a
# captured magic renders to an adapter call and almost every prefix has one.
_jumper_state = _jumper.new_state()
_jumper.attach_adapter(_jumper_state, "checkpoint")
_jumper_started = _jumper_time.perf_counter()
'''

_CHECKPOINT_FOOTER = '''
_jumper.checkpoint(
    _jumper_state,
    {paths!r},
    {max_bytes!r},
    _jumper_time.perf_counter() - _jumper_started,
)
'''

_RESTORE_HEADER = '''\
#!/usr/bin/env python3
"""Auto-generated by the JUmPER AI reviewer benchmark. Not meant to be edited."""
from jumper_extension.adapters.ai_reviewer.benchmark import dill_state as _jumper
from jumper_extension.adapters.ai_reviewer.benchmark.fingerprint import dump

# Restore first, monitor second: the load rebuilds a whole namespace, and the
# monitor has no business existing while it does. Only the target cell's window
# is sliced out of the samples, so starting late costs nothing.
_jumper_paths = _jumper.use_paths({paths!r})
_jumper_state, _jumper_restore_s = _jumper.restore(_jumper_paths)
_jumper.report_restore({restore_report!r}, _jumper_restore_s)
_jumper.write_phase(_jumper_paths["phase"], "setup")
_jumper.attach_adapter(_jumper_state, "restore")
_jumper_state.magic_adapter.perfmonitor_start({interval!r})
# Last thing before the cell: anything above could have consumed the generators.
_jumper.restore_rng(_jumper_paths["rng"], _jumper.META.get("rng"))
_jumper.write_phase(_jumper_paths["phase"], "cell_started")
_jumper.run_cell(_jumper_state, {target_code!r})
'''

_RESTORE_FOOTER = '''
# The cell is over; everything below is this benchmark's own work, and a failure
# in it must not be reported as the suggestion's.
_jumper.write_phase(_jumper_paths["phase"], "cell_finished")
dump({names!r}, vars(_jumper_state), {fingerprint_path!r})
_jumper_state.magic_adapter.perfmonitor_stop("")
_jumper.write_phase(_jumper_paths["phase"], "exporting")
_jumper_state.magic_adapter.export_session({session_path!r})
_jumper.write_phase(_jumper_paths["phase"], "completed")
'''


def render_cell(raw_cell: str, cell_magics: list[str]) -> str:
    """Render one cell as the hooks + code the replay script executes."""
    magics = list(cell_magics or [])
    return (
        f"magic_adapter.on_pre_run_cell("
        f"{raw_cell!r}, {magics!r}, {is_pure_magic_cell(raw_cell)!r})\n"
        f"{transform_cell_code(raw_cell, magics)}\n"
        f"magic_adapter.on_post_run_cell('')\n"
    )


def build_prefix_script(prefix_cells: list[dict], output_path: str) -> str:
    """Render just the prefix cells, for a runtime that brings its own adapter.

    The fork zygote runs the prefix once and then forks per measurement, so it
    owns the monitor and the session export itself and needs nothing from the
    header or the footer - only the cells, driven through the same hooks the
    full replay uses, so the state they build is the state it builds.
    """
    parts = []
    for cell in prefix_cells:
        parts.append("\n" + _PREFIX_MARKER.format(index=cell["index"]) + "\n")
        parts.append(render_cell(cell["raw_cell"], cell.get("cell_magics")))

    return _write(output_path, "".join(parts))


def build_checkpoint_script(
    prefix_cells: list[dict],
    paths: dict,
    max_bytes: int,
    output_path: str,
) -> str:
    """Write the script that runs the prefix once and checkpoints what it built.

    It measures nothing: no monitor is started and no session is exported. The
    screening, the RNG capture and the capped dump all happen inside
    ``dill_state.checkpoint`` rather than in this generated source, so they can be
    tested by calling them.
    """
    parts = [_CHECKPOINT_HEADER]
    for cell in prefix_cells:
        parts.append(
            f"\n_jumper.run_cell(_jumper_state, {cell['raw_cell']!r}, "
            f"{list(cell.get('cell_magics') or [])!r}, {cell['index']!r})\n"
        )
    parts.append(_CHECKPOINT_FOOTER.format(paths=paths, max_bytes=max_bytes))
    return _write(output_path, "".join(parts))


def build_restore_script(
    paths: dict,
    target_code: str,
    interval: float,
    fingerprint_names: list[str],
    session_path: str,
    fingerprint_path: str,
    restore_report_path: str,
    output_path: str,
) -> str:
    """Write the script that restores a checkpoint and times one cell on top of it.

    The prefix is not replayed here - that is the whole point - so the cell under
    test is the only entry in the exported history, at index 0.
    """
    parts = [
        _RESTORE_HEADER.format(
            paths=paths,
            restore_report=restore_report_path,
            interval=str(interval),
            target_code=target_code,
        ),
        _RESTORE_FOOTER.format(
            names=fingerprint_names,
            fingerprint_path=fingerprint_path,
            session_path=session_path,
        ),
    ]
    return _write(output_path, "".join(parts))


def build_script(
    prefix_cells: list[dict],
    target_code: str,
    interval: float,
    fingerprint_names: list[str],
    session_path: str,
    fingerprint_path: str,
    output_path: str,
) -> str:
    """Write a replay script: every prefix cell, then *target_code* last.

    The prefix is replayed in full because the target cell only means anything
    with the state its predecessors built. Returns *output_path*.
    """
    parts = [_HEADER.format(interval=str(interval))]
    for cell in prefix_cells:
        parts.append("\n" + _PREFIX_MARKER.format(index=cell["index"]) + "\n")
        parts.append(render_cell(cell["raw_cell"], cell.get("cell_magics")))
    parts.append("\n" + _TARGET_MARKER + "\n")
    parts.append(render_cell(target_code, []))
    parts.append(
        _FOOTER.format(
            names=fingerprint_names,
            fingerprint_path=fingerprint_path,
            session_path=session_path,
        )
    )

    return _write(output_path, "".join(parts))


def failing_prefix_cell(script_path: str, error: str) -> int | None:
    """The prefix cell a replay's traceback points at, or None.

    A replay that dies in the prefix has measured nothing and has said nothing
    about the code under review - it could not even get as far as running it - so
    reporting that failure against the suggestion sends the repair loop to fix
    code that never executed. The markers written above each cell are what makes
    the two distinguishable after the fact.

    None means the traceback is in the cell under test, in the scaffolding around
    it, or nowhere this can resolve; in each of those the prefix is not the thing
    to blame.
    """
    frames = re.findall(rf'File "{re.escape(script_path)}", line (\d+)', error)
    if not frames:
        return None
    try:
        lines = Path(script_path).read_text(encoding="utf-8").splitlines()
    except OSError:
        return None

    # The last frame in this file is the innermost one still in generated code;
    # anything deeper belongs to a library the cell called.
    line = int(frames[-1])
    for candidate in reversed(lines[: min(line, len(lines))]):
        if candidate.strip() == _TARGET_MARKER:
            return None
        found = _CELL_MARKER.match(candidate.strip())
        if found:
            return int(found.group(1))
    return None


def failing_checkpoint_cell(error: str) -> int | None:
    """The prefix cell a checkpoint died in, read off its traceback.

    The checkpoint script does not lay cells out in a file - it hands each to
    ``dill_state.run_cell``, which compiles it as ``<cell N>``. That name is the
    only marker there is, and it is enough.
    """
    frames = re.findall(r'File "<cell (\d+)>"', error or "")
    return int(frames[-1]) if frames else None


def _write(output_path: str, source: str) -> str:
    """Put *source* at *output_path*, creating the directory. Returns the path."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")
    return str(path)
